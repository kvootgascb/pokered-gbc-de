"""Generate Extended's counterpart slots from the original Red/Blue map files."""

import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def wild_tables(version):
    result = {}
    for path in (ROOT / "data/wild/maps").glob("*.asm"):
        label = re.search(r"^(\w+):", path.read_text(), re.M)[1]
        rows = [[], []]
        rates = [0, 0]
        enabled = True
        terrain = None
        for raw in path.read_text().splitlines():
            line = raw.split(";")[0].strip()
            if line.startswith("IF DEF("):
                enabled = version.upper() in line
            elif line == "ENDC":
                enabled = True
            elif enabled:
                m = re.match(r"def_(grass|water)_wildmons (\d+)", line)
                if m:
                    terrain = int(m[1] == "water")
                    rates[terrain] = int(m[2])
                m = re.match(r"db\s+(\d+),\s+(\w+)$", line)
                if m:
                    rows[terrain].append((int(m[1]), m[2]))
        for kind in (0, 1):
            assert len(rows[kind]) == (10 if rates[kind] else 0), path
        result[label] = (rates, rows)
    return result


def map_tables():
    text = (
        (ROOT / "data/wild/grass_water.asm").read_text().split("assert_table_length")[0]
    )
    return re.findall(r"^\s*dw (\w+)", text, re.M)


def overrides(version):
    own, other = wild_tables(version), wild_tables(
        "blue" if version == "red" else "red"
    )
    entries = []
    for map_id, name in enumerate(map_tables()):
        rates, rows = own[name]
        other_rates, other_rows = other[name]
        assert rates == other_rates, name
        for terrain in (0, 1):
            for slot, (before, after) in enumerate(
                zip(rows[terrain], other_rows[terrain])
            ):
                if before != after:
                    entries.append((map_id, terrain, slot * 2, *after))
    return entries


def generated():
    lines = [
        "; Generated by python tools/expanded_wild.py; original map files are authoritative.",
        "ExtendedWildOverrides::",
        "IF DEF(_RED)",
    ]
    for version in ("red", "blue"):
        if version == "blue":
            lines.append("ELSE")
        for map_id, terrain, slot, level, species in overrides(version):
            lines.append(f"\tdb ${map_id:02x}, {terrain}, {slot}, {level}, {species}")
    return "\n".join(lines + ["ENDC", "\tdb $ff ; end", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "data/wild/extended_overrides.asm"
    expected = generated()
    if args.check:
        assert path.read_text() == expected, "Regenerate Extended wild overrides"
        print(
            "PASS: Extended counterpart slots match the original Red/Blue source tables"
        )
    else:
        path.write_text(expected)
        print(f'Generated {len(overrides("red"))} counterpart slots per version')
